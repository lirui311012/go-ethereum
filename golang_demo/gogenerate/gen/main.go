// 生成器本身是普通的 Go 程序。go generate 只负责把它启动起来。
//
// 它不使用 reflect。reflect 要等程序跑起来、值已经装进接口才能看类型。
// 生成(generate)发生在反射(reflect)之前：这里用 go/parser 读源码，看到结构体的字段名和类型写法，
// 再把对应的方法调用打印成一个新的 .go 文件。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	typeName := flag.String("type", "", "要生成方法的结构体名")
	out := flag.String("out", "", "输出文件")
	flag.Parse()
	if *typeName == "" || *out == "" {
		fatal(fmt.Errorf("需要 -type 和 -out"))
	}

	// go generate 的工作目录是写有 //go:generate 的那个包。
	// 输出文件不再解析，避免把上次生成的方法当成输入。
	files, fset, err := parseGoFiles(".", *out)
	if err != nil {
		fatal(err)
	}
	// ast.File.Name 是包名（package main），路径在 FileSet 里。
	for _, f := range files {
		fmt.Println(fset.File(f.Pos()).Name())
	}

	st, err := findStruct(files, *typeName)
	if err != nil {
		fatal(err)
	}
	fields, err := exportedFields(st)
	if err != nil {
		fatal(err)
	}

	source, err := render(*typeName, fields)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*out, source, 0o644); err != nil {
		fatal(err)
	}

	fmt.Printf("gendemo: 已写入 %s", *out)
	for i, f := range fields {
		if i == 0 {
			fmt.Print("，字段 ")
		} else {
			fmt.Print("，")
		}
		fmt.Printf("%s %s", f.name, f.kind)
	}
	fmt.Println()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gendemo:", err)
	os.Exit(1)
}

type field struct {
	name string
	kind string
}

// parseGoFiles 用 ParseFile 逐个读目录里的 .go 文件。
// 本目录没有构建标签，文件名以 .go 结尾的都参与生成。
func parseGoFiles(dir, skip string) ([]*ast.File, *token.FileSet, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, nil, err
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || name == skip {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, 0)
		if err != nil {
			return nil, nil, err
		}
		files = append(files, f)
	}
	if len(files) == 0 {
		return nil, nil, fmt.Errorf("%s 里没有可解析的 Go 源文件", dir)
	}
	return files, fset, nil
}

func findStruct(files []*ast.File, name string) (*ast.StructType, error) {
	var found *ast.StructType
	for _, file := range files {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if ts.Name.Name != name {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					return nil, fmt.Errorf("%s 不是结构体", name)
				}
				if found != nil {
					return nil, fmt.Errorf("类型 %s 出现了多次", name)
				}
				found = st
			}
		}
	}
	if found == nil {
		return nil, fmt.Errorf("找不到类型 %s", name)
	}
	return found, nil
}

func exportedFields(st *ast.StructType) ([]field, error) {
	var out []field
	for _, f := range st.Fields.List {
		if len(f.Names) == 0 {
			return nil, fmt.Errorf("这个示例不处理嵌入字段")
		}
		for _, name := range f.Names {
			if !token.IsExported(name.Name) {
				fmt.Printf("gendemo: 跳过未导出字段 %s\n", name.Name)
				continue
			}
			kind, err := fieldKind(f.Type)
			if err != nil {
				return nil, fmt.Errorf("字段 %s: %w", name.Name, err)
			}
			out = append(out, field{name: name.Name, kind: kind})
		}
	}
	return out, nil
}

// fieldKind 只看源码里的类型写法。uint64、string、[]byte 够这个示例用。
// common.Hash、*big.Int 这种别的包里的具名类型，单看写法不知道底层是什么，
// rlpgen 因此会去做完整的类型检查，而不是停在语法树上。
func fieldKind(e ast.Expr) (string, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if t.Name == "uint64" || t.Name == "string" {
			return t.Name, nil
		}
	case *ast.ArrayType:
		elt, ok := t.Elt.(*ast.Ident)
		if t.Len == nil && ok && elt.Name == "byte" {
			return "[]byte", nil
		}
	}
	return "", fmt.Errorf("只支持 uint64、string、[]byte，看到 %s", exprString(e))
}

func exprString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.ArrayType:
		return "[]" + exprString(t.Elt)
	case *ast.StarExpr:
		return "*" + exprString(t.X)
	case *ast.SelectorExpr:
		return exprString(t.X) + "." + t.Sel.Name
	default:
		return fmt.Sprintf("%T", e)
	}
}

func render(typeName string, fields []field) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gendemo. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package main\n\n")
	fmt.Fprintf(&b, "// EncodeGen 按 %s 的导出字段顺序写字节。\n", typeName)
	fmt.Fprintf(&b, "// 字段列表在 go generate 时定死，调用这个方法时不再查看类型。\n")
	fmt.Fprintf(&b, "func (obj *%s) EncodeGen(w *Writer) {\n", typeName)
	for _, f := range fields {
		switch f.kind {
		case "uint64":
			fmt.Fprintf(&b, "\tw.Uint64(obj.%s)\n", f.name)
		case "string":
			fmt.Fprintf(&b, "\tw.String(obj.%s)\n", f.name)
		case "[]byte":
			fmt.Fprintf(&b, "\tw.Bytes(obj.%s)\n", f.name)
		default:
			return nil, fmt.Errorf("无法为 %s 生成代码", f.kind)
		}
	}
	fmt.Fprintf(&b, "}\n")
	return format.Source(b.Bytes())
}
